function egitimsablonsaatuyumu(tehlikeSinifi)
{
    tehlikeSinifi = String(tehlikeSinifi || '');
    if (!['1', '2', '3'].includes(tehlikeSinifi))
    {
        return [];
    }
    return egitimsablonbuljson('sablon').filter(function (item)
    {
        var saat = parseInt(item && item.s ? item.s : 0, 10);
        if (tehlikeSinifi === '1')
        {
            return saat >= 8;
        }
        if (tehlikeSinifi === '2')
        {
            return saat >= 12;
        }
        return saat >= 16;
    });
}

