function sablonkonularinibul(seciliSablon)
{
    var hazirKonular = [];
    var konuGruplari = Array.isArray(seciliSablon?.x) ? seciliSablon.x : [];
    var tehlikeSinifi = String(seciliSablon?.t ?? '').trim();
    var kaynak = temelisgkonulistesi(tehlikeSinifi);
    konuGruplari.forEach(function (grup)
    {
        var tip = parseInt(grup?.t, 10);
        var gun = parseInt(grup?.g, 10);
        var konular = Array.isArray(grup?.x) ? grup.x : [];
        konular.forEach(function (item)
        {
            var konu = '';
            if (item?.konu)
            {
                konu = String(item.konu).trim();
            }
            else
            {
                var konuId = parseInt(item?.k, 10);
                var kayit = kaynak.find(function (x)
                {
                    return parseInt(x.tip, 10) === tip && parseInt(x.id, 10) === konuId;
                });
                konu = kayit?.konu  ? String(kayit.konu).trim() : '';
            }
            if (!konu) { return; }
            hazirKonular.push
            ({
                t: tip,
                k: item.k,
                s: item.s,
                g: gun,
                konu: konu
            });
        });
    });
    return hazirKonular;
}

