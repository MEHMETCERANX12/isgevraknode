function sablonsaategoresiralama(liste, saateGore)
{
    return (Array.isArray(liste) ? liste.slice() : []).sort(function (a, b)
    {
        if (saateGore)
        {
            var saatA = parseInt(a && a.s ? a.s : 0, 10);
            var saatB = parseInt(b && b.s ? b.s : 0, 10);
            if (saatA !== saatB)
            {
                return saatA - saatB;
            }
        }
        var adA = String(a && a.i ? a.i : '').toLocaleLowerCase('tr-TR');
        var adB = String(b && b.i ? b.i : '').toLocaleLowerCase('tr-TR');
        return adA.localeCompare(adB, 'tr');
    });
}

